"""Промпт судьи. Одна LLM-проверка на весь текст: подаём все судейские
правила разом, получаем один JSON-массив находок. Дёшево (один вызов) и
контекст правил виден целиком.
"""
from __future__ import annotations

from .rules import JudgeRule

SYSTEM = (
    "Ты — придирчивый редактор. Проверяешь ЧЕРНОВИК против КАНОНА и находишь "
    "СМЫСЛОВЫЕ нарушения — те, что не ловятся простым поиском слов: перефразы, "
    "интонация, скрытые противопоставления, несоответствие обложки тексту. "
    "Отвечай ТОЛЬКО валидным JSON, без пояснений и markdown."
)


def _rule_block(r: JudgeRule) -> str:
    lines = [f"- rule_id: {r.id}  (пункт канона {r.point}, severity: {r.severity})",
             f"  суть: {r.message or r.id}"]
    if r.judgment_extends:
        lines.append("  режим: буквальные формы УЖЕ пойманы отдельно — ищи только "
                     "смысловые ВАРИАЦИИ (перефраз, непрямая форма).")
    else:
        lines.append("  режим: чисто смысловое правило, буквального аналога нет.")
    if r.literal_markers:
        shown = ", ".join(r.literal_markers[:8])
        lines.append(f"  уже покрыто буквально (НЕ повторять эти попадания): {shown}")
    if r.fix:
        lines.append(f"  как чинить: {r.fix}")
    if r.note:
        lines.append(f"  заметка: {r.note}")
    return "\n".join(lines)


def build_prompt(text: str, rules: list[JudgeRule]) -> str:
    rules_txt = "\n\n".join(_rule_block(r) for r in rules)
    return f"""КАНОН — смысловые правила для проверки:

{rules_txt}

ЧЕРНОВИК (проверяй его целиком):
<<<
{text}
>>>

Верни JSON-массив находок. Каждая находка:
{{
  "rule_id": "<id одного из правил выше>",
  "quote": "<ДОСЛОВНАЯ подстрока черновика, которую нарушает правило — копируй символ в символ, коротко, 3-15 слов>",
  "reason": "<в одной фразе, почему это нарушение именно этого правила>",
  "fix": "<как переписать>",
  "confidence": <число 0..1>
}}

Требования:
- quote — ТОЧНАЯ подстрока черновика (иначе находку нельзя привязать к месту);
- не выдумывай нарушений: пустой массив [] — нормальный ответ для чистого текста;
- не дублируй то, что уже покрыто буквально;
- только JSON-массив, ничего вокруг."""
